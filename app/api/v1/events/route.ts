function buildLookupEnvelope(query: EventQuery, generatedAt: string) {
  const requestHash = sha256(
    JSON.stringify({
      endpoint: "GET /api/v1/events",
      eventId: query.eventId,
      humanIpr: query.humanIpr,
      runtimeIpr: query.runtimeIpr,
      tenant: query.tenant,
      workspace: query.workspace,
      limit: query.limit,
      generatedAt
    })
  );

  return {
    status: query.eventId
      ? "EVT_LOOKUP_NOT_PERSISTED_BY_THIS_ROUTE"
      : "EVT_LEDGER_LIST_NOT_PERSISTED_BY_THIS_ROUTE",
    lookupMode: "CONTRACT_RECEIPT_ONLY",
    persistenceMode: "NO_DATABASE_LOOKUP_IN_THIS_ROUTE",
    eventKnownByThisRoute: false,
    databaseReadPerformed: false,
    eventCreated: false,
    opcCreated: false,
    auditCreated: false,
    usageCreated: false,
    requestedEventId: query.eventId,
    requestedLimit: query.limit,
    returnedEvents: [],
    returnedCount: 0,
    requestHash,
    note:
      "Runtime EVT records remain owned by the internal EVT ledger. This v1 public endpoint defines the external contract and safe lookup envelope. Database-backed lookup can be wired later without changing the public shape."
  };
}

function buildSampleEvent(query: EventQuery, generatedAt: string) {
  const eventSeed = JSON.stringify({
    eventType: "GOVERNED_CHAT_RESPONSE",
    subjectIpr: query.humanIpr,
    runtimeIpr: query.runtimeIpr,
    tenant: query.tenant,
    workspace: query.workspace,
    createdAt: generatedAt,
    legalCertification: LEGAL_CERTIFICATION,
    opcBoundary: OPC_BOUNDARY
  });

  return {
    eventId: "EVT-V1-SAMPLE-GOVERNED-CHAT-RESPONSE",
    eventType: "GOVERNED_CHAT_RESPONSE",
    subjectIpr: query.humanIpr,
    runtimeIpr: query.runtimeIpr,
    tenant: query.tenant,
    workspace: query.workspace,
    createdAt: generatedAt,
    eventHash: sha256(eventSeed),
    linkedOpcId: "OPC-V1-SAMPLE-TECHNICAL-PROOF-RECEIPT",
    linkedAuditId: "AUDIT-V1-SAMPLE-RUNTIME-AUDIT-LOG",
    linkedUsageId: "USAGE-V1-SAMPLE-MODEL-USAGE-LOG",
    legalCertification: LEGAL_CERTIFICATION,
    opcBoundary: OPC_BOUNDARY
  };
}

export async function GET(request: NextRequest): Promise<NextResponse> {
  const generatedAt = isoNow();
  const query = normalizeEventQuery(request);

  return NextResponse.json(
    {
      status: "HBCE_IPR_RUNTIME_EVENTS_CONTRACT_READY",
      revision: ROUTE_REVISION,
      generatedAt,
      product: PRODUCT_NAME,
      apiVersion: API_VERSION,
      runtime: RUNTIME_NAME,
      identity: {
        humanIpr: query.humanIpr,
        runtimeIpr: query.runtimeIpr,
        tenant: query.tenant,
        workspace: query.workspace,
        access: "ACCESS_GRANTED",
        identityBinding: "IPR_OPERATIONAL_IDENTITY_BOUND"
      },
      eventLedger: buildEventContract(),
      lookup: buildLookupEnvelope(query, generatedAt),
      sampleEventShape: buildSampleEvent(query, generatedAt),
      temporalSeal: buildTemporalSeal(generatedAt),
      publicSurface: buildPublicSurface(),
      boundary: buildBoundary()
    },
    {
      status: 200,
      headers: {
        "Cache-Control": "no-store",
        "X-HBCE-API-Version": API_VERSION,
        "X-HBCE-Route-Revision": ROUTE_REVISION,
        "X-HBCE-Legal-Certification": "false",
        "X-HBCE-OPC-Boundary": OPC_BOUNDARY
      }
    }
  );
}
