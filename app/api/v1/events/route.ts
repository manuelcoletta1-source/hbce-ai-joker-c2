import { createHash } from "node:crypto";
import { NextRequest, NextResponse } from "next/server";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

const ROUTE_REVISION = "HBCE-IPR-RUNTIME-API-v1-EVENTS-CONTRACT-v0.1";
const API_VERSION = "v1";
const PRODUCT_NAME = "HBCE IPR Operational Identity & Proof Layer";
const RUNTIME_NAME = "AI_JOKER_C2_SAAS_CORE_v0_1";

const DEFAULT_HUMAN_IPR = "IPR-88505FE91013DCFE97C56ED1";
const DEFAULT_RUNTIME_IPR = "IPR-AI-0001";
const DEFAULT_TENANT = "HBCE-TENANT-SELF-PILOT";
const DEFAULT_WORKSPACE = "HBCE-WORKSPACE-RND";

const LEGAL_CERTIFICATION = false;
const OPC_BOUNDARY = "technical proof receipt only";
const IPR_CARD_BOUNDARY =
  "IPR Card is an internal operational identity certificate, not an official public identity document.";

const EVENT_LEDGER_BOUNDARY =
  "This public v1 route exposes the EVT contract and lookup envelope only. It does not perform database reads or create new runtime events.";

const SUPPORTED_EVENT_TYPES = [
  "IPR_SESSION_OPENED",
  "GOVERNED_CHAT_RESPONSE",
  "OPERATION_ACCEPTED",
  "OPERATION_STATUS_LOOKUP",
  "FILE_INGESTION_RECEIPT",
  "SOURCE_INTELLIGENCE_SUMMARY",
  "OPC_TECHNICAL_PROOF_RECEIPT",
  "AUDIT_LOG_RECORD",
  "MODEL_USAGE_RECORD"
] as const;

type EventQuery = {
  eventId: string | null;
  humanIpr: string;
  runtimeIpr: string;
  tenant: string;
  workspace: string;
  limit: number;
};

function isoNow(): string {
  return new Date().toISOString();
}

function sha256(value: string): string {
  return `sha256:${createHash("sha256").update(value, "utf8").digest("hex")}`;
}

function safeString(value: string | null): string | null {
  if (typeof value !== "string") return null;
  const trimmed = value.trim();
  return trimmed.length > 0 ? trimmed : null;
}

function boundedInteger(value: string | null, fallback: number, min: number, max: number): number {
  if (!value) return fallback;
  const parsed = Number.parseInt(value, 10);
  if (!Number.isFinite(parsed)) return fallback;
  return Math.max(min, Math.min(max, parsed));
}

function normalizeEventQuery(request: NextRequest): EventQuery {
  const params = request.nextUrl.searchParams;

  return {
    eventId: safeString(params.get("eventId")),
    humanIpr: safeString(params.get("humanIpr")) ?? DEFAULT_HUMAN_IPR,
    runtimeIpr: safeString(params.get("runtimeIpr")) ?? DEFAULT_RUNTIME_IPR,
    tenant: safeString(params.get("tenant")) ?? DEFAULT_TENANT,
    workspace: safeString(params.get("workspace")) ?? DEFAULT_WORKSPACE,
    limit: boundedInteger(params.get("limit"), 25, 1, 100)
  };
}

